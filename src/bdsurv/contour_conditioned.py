r"""Simulate birth-death trees conditioned on the population alive at ``T``.

The contour of a tree with ``n`` individuals alive at ``T`` is built from
independent pieces: one first-passage piece from ``0`` to ``T``, ``n - 1``
excursions from ``T`` back to ``T``, and one piece from ``T`` to ``0``.
Rates may be scalars or piecewise constant / linear in time; the pieces are
generated by hazard inversion at the absolute time of each jump, with
downward jumps driven by the birth rate and upward jumps by the death rate.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

import numpy as np

from bdsurv import _linear_math
from bdsurv._linear_math import Rate
from bdsurv._numerics import close
from bdsurv.contour import (
    _contour_process_list_to_tree,  # pyright: ignore[reportPrivateUsage]
    _seeded_rng,  # pyright: ignore[reportPrivateUsage]
    _validate_contour_process_list,  # pyright: ignore[reportPrivateUsage]
)
from bdsurv.linear_rates import ConstantRateLike, LinearRateLike, PiecewiseConstant
from bdsurv.tree import SimulatedTree

RateInput = float | ConstantRateLike | LinearRateLike
Direction = Literal["auto", "top", "bottom"]

_DIRECTIONS = ("auto", "top", "bottom")
_END_PIECES = 2


@dataclass(frozen=True)
class _Rates:
    """Validated rates in array form, with the arguments for the decoded tree."""

    birth: Rate
    death: Rate
    terminal_time: float
    tree_args: dict[str, object]


def _is_scalar(rate: RateInput) -> bool:
    return isinstance(rate, int | float)


def _resolve_rates(
    birth_rate: RateInput, death_rate: RateInput, terminal_time: float | None
) -> _Rates:
    """Convert the rate inputs to :class:`Rate` arrays and fix the end time ``T``."""
    if terminal_time is not None and terminal_time <= 0.0:
        msg = "terminal_time must be positive"
        raise ValueError(msg)
    ends = [
        float(np.atleast_1d(np.asarray(r.epoch_end_times, dtype=np.float64))[-1])
        for r in (birth_rate, death_rate)
        if not isinstance(r, int | float)
    ]
    if not ends:
        if terminal_time is None:
            msg = "terminal_time is required when both rates are floats"
            raise ValueError(msg)
        horizon = float(terminal_time)
    else:
        horizon = ends[0]
        if not all(np.isclose(horizon, e) for e in ends):
            msg = "birth and death rates must have the same end time"
            raise ValueError(msg)
        if terminal_time is not None and not np.isclose(horizon, terminal_time):
            msg = "terminal_time must equal the end time of the rates"
            raise ValueError(msg)
    if horizon <= 0.0:
        msg = "terminal_time must be positive"
        raise ValueError(msg)

    def wrap(rate: RateInput) -> ConstantRateLike | LinearRateLike:
        if isinstance(rate, int | float):
            return PiecewiseConstant([float(rate)], [horizon])
        return rate

    birth_like, death_like = wrap(birth_rate), wrap(death_rate)
    if _is_scalar(birth_rate) and _is_scalar(death_rate):
        tree_args: dict[str, object] = {
            "birth_rate": float(birth_rate),  # pyright: ignore[reportArgumentType]
            "death_rate": float(death_rate),  # pyright: ignore[reportArgumentType]
        }
    else:
        tree_args = {
            "birth_rate": float("nan"),
            "death_rate": float("nan"),
            "birth_rate_function": birth_like,
            "death_rate_function": death_like,
        }
    return _Rates(
        _linear_math.as_rate(birth_like),
        _linear_math.as_rate(death_like),
        horizon,
        tree_args,
    )


@dataclass(frozen=True)
class _Walker:
    """The step and run primitives of the contour construction.

    Downward jumps use the birth rate, upward jumps the death rate.
    A step never returns its start level, and endpoints are snapped exactly
    to ``0`` and ``T`` (the decoder compares with ``close``).
    """

    birth: Rate
    death: Rate
    terminal_time: float
    rng: np.random.Generator

    def down(self, x: float) -> float:
        """Return the next level below ``x``, snapped to ``0`` when close."""
        while True:
            s = _linear_math.backward_hazard_time(
                self.birth, x, float(self.rng.exponential())
            )
            if close(s, 0.0):
                s = 0.0
            if s != x:
                return s

    def up(self, y: float) -> float:
        """Return the next level above ``y``, snapped to ``T`` when close."""
        while True:
            s = _linear_math.forward_hazard_time(
                self.death, y, float(self.rng.exponential()), self.terminal_time
            )
            if close(s, self.terminal_time):
                s = self.terminal_time
            if s != y:
                return s

    def run(self, path: list[float], next_move: Literal["up", "down"]) -> list[float]:
        """Extend ``path`` by alternating moves until it reaches ``0`` or ``T``.

        A downward move ends the run at ``0`` and an upward move at ``T``.
        """
        while True:
            if next_move == "down":
                path.append(self.down(path[-1]))
                if path[-1] == 0.0:
                    return path
                next_move = "up"
            else:
                path.append(self.up(path[-1]))
                if path[-1] == self.terminal_time:
                    return path
                next_move = "down"

    def top_excursion(self) -> list[float]:
        """Run from ``T``; ends at ``T`` (``TT``) or at ``0`` (``T0``)."""
        return self.run([self.terminal_time], "down")

    def bottom_excursion(self) -> list[float]:
        """Run from ``0``; ends at ``T`` (``0T``) or at ``0`` (rejected by callers)."""
        return self.run([0.0], "up")


def _log_survival_pair(
    birth: Rate, death: Rate, terminal_time: float
) -> tuple[float, float]:
    """Return ``(log_S_fwd, log_S_rev)``, the log survival probabilities to ``T``.

    ``log_S_fwd`` is for the given rates and ``log_S_rev`` for the time-reversed
    rates ``(mu(T - t), lambda(T - t))``, using ``S_rev = S_fwd * exp(-Gamma(T))``.
    """
    log_s_fwd = _linear_math.log_survival_probability(birth, death, terminal_time)
    growth = float(
        _linear_math.cumulative(birth, terminal_time)
        - _linear_math.cumulative(death, terminal_time)
    )
    return log_s_fwd, log_s_fwd - growth


def _prefer_top(
    birth: Rate, death: Rate, terminal_time: float, direction: Direction
) -> bool:
    """Return whether to generate the end pieces from the top (``T``) end."""
    if direction not in _DIRECTIONS:
        msg = f"direction must be one of {_DIRECTIONS}, got {direction!r}"
        raise ValueError(msg)
    if direction != "auto":
        return direction == "top"
    log_s_fwd, log_s_rev = _log_survival_pair(birth, death, terminal_time)
    return log_s_rev > log_s_fwd


def _join_pieces(
    first: list[float], tt: list[list[float]], last: list[float]
) -> list[float]:
    """Join ``first`` (``0..T``), the ``T..T`` excursions and ``last`` (``T..0``)."""
    contour = list(first)
    for excursion in tt:
        contour.extend(excursion[1:])
    contour.extend(last[1:])
    return contour


def _population_contour(
    walker: _Walker, n_alive: int, *, prefer_top: bool
) -> list[float]:
    """Generate the contour of a tree with ``n_alive`` individuals alive at ``T``."""
    terminal_time = walker.terminal_time
    tt: list[list[float]] = []
    t0: list[list[float]] = []
    while len(tt) < n_alive - 1:
        excursion = walker.top_excursion()
        if excursion[-1] == terminal_time:
            tt.append(excursion)
        elif len(t0) < _END_PIECES:
            t0.append(excursion)
    zero_to_t: list[list[float]] = []
    if len(t0) < _END_PIECES:
        if prefer_top:
            while len(t0) < _END_PIECES:
                excursion = walker.top_excursion()
                if excursion[-1] == 0.0:
                    t0.append(excursion)
        else:
            while len(t0) + len(zero_to_t) < _END_PIECES:
                piece = walker.bottom_excursion()
                if piece[-1] == terminal_time:
                    zero_to_t.append(piece)
    pool = [piece[::-1] for piece in t0] + zero_to_t  # all oriented 0..T
    contour = _join_pieces(pool[0], tt, pool[1][::-1])
    _validate_contour_process_list(contour)
    if contour.count(terminal_time) != n_alive:
        msg = "contour does not have n_alive visits to the terminal time"
        raise AssertionError(msg)
    return contour


def simulate_contour_given_population(
    birth_rate: RateInput,
    death_rate: RateInput,
    n_alive: int,
    terminal_time: float | None = None,
    random_seed: int | None = None,
    direction: Direction = "auto",
) -> SimulatedTree:
    r"""Simulate a birth-death tree conditioned on ``n_alive`` individuals at ``T``.

    The contour is made of a ``0`` to ``T`` piece, ``n_alive - 1`` excursions
    from ``T`` to ``T`` and a ``T`` to ``0`` piece, all independent.
    The end pieces are generated from the end at which they are cheaper to
    obtain, chosen by comparing the extinction probabilities of the process and
    of its time reversal (equivalently the sign of $\Gamma(T)$).

    Parameters
    ----------
    birth_rate, death_rate
        Per-individual rates: floats (then ``terminal_time`` is required) or
        piecewise constant / linear rate-likes over ``[0, T]``.
    n_alive
        Number of individuals alive at ``T``; at least 1.
    terminal_time
        The time ``T``. For rate-like inputs it must be ``None`` or equal to
        their common end time.
    random_seed
        Seed for reproducibility.
    direction
        ``"auto"`` chooses the end of the end pieces; ``"top"`` or ``"bottom"``
        force it. All give the same distribution.

    Returns
    -------
    SimulatedTree
        For float rates the tree carries them as scalars; otherwise
        ``birth_rate`` and ``death_rate`` are NaN and the rates are in
        ``birth_rate_function`` and ``death_rate_function``.

    Raises
    ------
    ValueError
        If ``n_alive < 1``, ``T <= 0``, ``terminal_time`` is missing or does
        not match the rates, ``direction`` is invalid, or ``n_alive > 1`` and
        the birth rate is identically zero.

    """
    if n_alive < 1:
        msg = "n_alive must be at least 1"
        raise ValueError(msg)
    rates = _resolve_rates(birth_rate, death_rate, terminal_time)
    prefer_top = _prefer_top(rates.birth, rates.death, rates.terminal_time, direction)
    if n_alive > 1 and _linear_math.cumulative(rates.birth, rates.terminal_time) <= 0.0:
        msg = "birth_rate must not be identically zero when n_alive > 1"
        raise ValueError(msg)
    walker = _Walker(
        rates.birth, rates.death, rates.terminal_time, _seeded_rng(random_seed)
    )
    contour = _population_contour(walker, n_alive, prefer_top=prefer_top)
    return _contour_process_list_to_tree(contour, **rates.tree_args)  # pyright: ignore[reportArgumentType]
