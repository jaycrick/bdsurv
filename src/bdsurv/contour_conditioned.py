r"""Simulate birth-death trees conditioned on the population alive at ``T``.

The contour of a tree with ``n`` individuals alive at ``T`` is built from
independent pieces: one first-passage piece from ``0`` to ``T``, ``n - 1``
excursions from ``T`` back to ``T``, and one piece from ``T`` to ``0``.
Rates may be scalars or piecewise constant / linear in time; the pieces are
generated by hazard inversion at the absolute time of each jump, with
downward jumps driven by the birth rate and upward jumps by the death rate.
The stepper (:class:`bdsurv.contour.Walker`) and the piece-joining and
rejection helpers live in :mod:`bdsurv.contour`; the contour is validated once,
by the decoder.
"""

from __future__ import annotations

from collections.abc import Sequence
from typing import Literal

import numpy as np

from bdsurv._hazard import close, cumulative, log_integral, log_survival_probability
from bdsurv._seeding import root_rng
from bdsurv.contour import (
    Walker,
    contour_process_list_to_tree,
    join_pieces,
    sample_until,
)
from bdsurv.rates import Rate, RateInput, as_rate_like, resolve_rates
from bdsurv.tree import SimulatedTree

Direction = Literal["auto", "top", "bottom"]

_DIRECTIONS = ("auto", "top", "bottom")
_END_PIECES = 2


def _log_survival_pair(
    birth: Rate, death: Rate, terminal_time: float
) -> tuple[float, float]:
    """Return ``(log_S_fwd, log_S_rev)``, the log survival probabilities to ``T``.

    ``log_S_fwd`` is for the given rates and ``log_S_rev`` for the time-reversed
    rates ``(mu(T - t), lambda(T - t))``, using ``S_rev = S_fwd * exp(-Gamma(T))``.
    """
    log_s_fwd = log_survival_probability(birth, death, terminal_time)
    growth = float(cumulative(birth, terminal_time) - cumulative(death, terminal_time))
    return log_s_fwd, log_s_fwd - growth


def _prefer_top(
    birth: Rate, death: Rate, terminal_time: float, direction: Direction
) -> bool:
    """Return whether to generate the end pieces from the top (``T``) end."""
    if direction not in _DIRECTIONS:
        msg = f"direction must be one of {_DIRECTIONS}, got {direction!r}"
        raise ValueError(msg)
    if direction != "auto":
        return direction == "top"
    log_s_fwd, log_s_rev = _log_survival_pair(birth, death, terminal_time)
    return log_s_rev > log_s_fwd


def _population_contour(
    walker: Walker, n_alive: int, *, prefer_top: bool
) -> list[float]:
    """Generate the contour of a tree with ``n_alive`` individuals alive at ``T``."""
    terminal_time = walker.terminal_time
    tt: list[list[float]] = []
    t0: list[list[float]] = []
    while len(tt) < n_alive - 1:
        excursion = walker.top_excursion()
        if excursion[-1] == terminal_time:
            tt.append(excursion)
        elif len(t0) < _END_PIECES:
            t0.append(excursion)
    zero_to_t: list[list[float]] = []
    missing = _END_PIECES - len(t0)
    if prefer_top:
        t0 += [
            sample_until(walker.top_excursion, lambda piece: piece[-1] == 0.0)
            for _ in range(missing)
        ]
    else:
        zero_to_t = [
            sample_until(
                walker.bottom_excursion, lambda piece: piece[-1] == terminal_time
            )
            for _ in range(missing)
        ]
    pool = [piece[::-1] for piece in t0] + zero_to_t  # all oriented 0..T
    contour = join_pieces(pool[0], tt, pool[1][::-1])
    if contour.count(terminal_time) != n_alive:
        msg = "contour does not have n_alive visits to the terminal time"
        raise AssertionError(msg)
    return contour


def simulate_contour_given_population(
    birth_rate: RateInput,
    death_rate: RateInput,
    n_alive: int,
    terminal_time: float | None = None,
    random_seed: int | None = None,
    *,
    direction: Direction = "auto",
) -> SimulatedTree:
    r"""Simulate a birth-death tree conditioned on ``n_alive`` individuals at ``T``.

    The contour is made of a ``0`` to ``T`` piece, ``n_alive - 1`` excursions
    from ``T`` to ``T`` and a ``T`` to ``0`` piece, all independent.
    The end pieces are generated from the end at which they are cheaper to
    obtain, chosen by comparing the extinction probabilities of the process and
    of its time reversal (equivalently the sign of $\Gamma(T)$).

    Parameters
    ----------
    birth_rate, death_rate
        Per-individual rates: floats (then ``terminal_time`` is required) or
        piecewise constant / linear rate-likes over ``[0, T]``.
    n_alive
        Number of individuals alive at ``T``; at least 1.
    terminal_time
        The time ``T``. For rate-like inputs it must be ``None`` or equal to
        their common end time.
    random_seed
        Seed for reproducibility.
    direction
        ``"auto"`` chooses the end of the end pieces; ``"top"`` or ``"bottom"``
        force it. All give the same distribution. Keyword-only.

    Returns
    -------
    SimulatedTree
        The tree with one spine survivor.
        Its ``birth_rate`` and ``death_rate`` are the rate objects (a float
        rate as a one-epoch :class:`~bdsurv.rates.PiecewiseConstant`).

    Raises
    ------
    ValueError
        If ``n_alive < 1``, ``T <= 0``, ``terminal_time`` is missing or does
        not match the rates, ``direction`` is invalid, or ``n_alive > 1`` and
        the birth rate is identically zero.

    """
    if n_alive < 1:
        msg = "n_alive must be at least 1"
        raise ValueError(msg)
    birth, death, horizon = resolve_rates(birth_rate, death_rate, terminal_time)
    prefer_top = _prefer_top(birth, death, horizon, direction)
    if n_alive > 1 and cumulative(birth, horizon) <= 0.0:
        msg = "birth_rate must not be identically zero when n_alive > 1"
        raise ValueError(msg)
    walker = Walker(birth, death, horizon, root_rng(random_seed, "contour"))
    contour = _population_contour(walker, n_alive, prefer_top=prefer_top)
    return contour_process_list_to_tree(
        contour,
        birth_rate=as_rate_like(birth_rate, horizon),
        death_rate=as_rate_like(death_rate, horizon),
    )


def _spine_levels(ages: Sequence[float], terminal_time: float) -> list[float]:
    """Return levels ``b_i = T - a_i``, exactly ``0`` for ages close to ``T``."""
    return [0.0 if close(a, terminal_time) else terminal_time - a for a in ages]


def _log_spine_weights(
    birth: Rate, death: Rate, terminal_time: float, ages: Sequence[float]
) -> np.ndarray:
    r"""Return $\ln w_i$ with $w_i = (I(T) - I(b_i)) / (1 + I(b_i))$, $b_i = T - a_i$.

    Here $I(t) = \int_0^t \mu(s) e^{-\Gamma(s)} ds$; ``-inf`` entries are allowed.
    """
    log_i_t = log_integral(death, birth, death, terminal_time, sign=-1.0)
    out = np.full(len(ages), -np.inf)
    if log_i_t == -np.inf:
        return out
    for i, b in enumerate(_spine_levels(ages, terminal_time)):
        log_i_b = log_integral(death, birth, death, b, sign=-1.0)
        with np.errstate(divide="ignore"):
            log_num = log_i_t + np.log(-np.expm1(min(log_i_b - log_i_t, 0.0)))
        out[i] = log_num - np.logaddexp(0.0, log_i_b)
    return out


def _cut_at_last_downcrossing(path: list[float], level: float) -> list[float] | None:
    """Cut ``path`` at its last down-crossing of ``level``, ending ``[..., level, T]``.

    A down-crossing is an odd ``j < len(path) - 1`` with
    ``path[j] > level > path[j + 1]``. Return ``None`` when there is none.
    """
    crossings = [j for j in range(1, len(path) - 1, 2) if path[j] > level > path[j + 1]]
    if not crossings:
        return None
    return [*path[: max(crossings) + 1], level, path[-1]]


def _choose_spine(
    walker: Walker,
    ages: Sequence[float],
    levels: Sequence[float],
    spine_index: int | None,
) -> int:
    """Return the index of the age assigned to the spine.

    ``spine_index`` is used when given. Otherwise an age at ``T`` (level ``0``)
    forces the spine, and else the spine is sampled with the weights of
    :func:`_log_spine_weights`.

    Raises
    ------
    ValueError
        If all spine weights are zero.
    """
    if spine_index is not None:
        return spine_index
    forced = [i for i, b in enumerate(levels) if b == 0.0]
    if forced:
        return forced[0]
    log_w = _log_spine_weights(walker.birth, walker.death, walker.terminal_time, ages)
    if not np.any(np.isfinite(log_w)):
        msg = "all spine weights are zero"
        raise ValueError(msg)
    weights = np.exp(log_w - np.max(log_w))
    return int(walker.rng.choice(len(ages), p=weights / weights.sum()))


def _non_spine_excursions(
    walker: Walker, levels: Sequence[float], spine_index: int
) -> list[list[float]]:
    """Return one ``T`` to ``T`` excursion ending at each non-spine level.

    Each is a run up from its level that reaches ``T``, reversed and closed
    with ``T``; they are drawn in index order.
    """
    terminal_time = walker.terminal_time
    excursions: list[list[float]] = []
    for i, b in enumerate(levels):
        if i == spine_index:
            continue
        piece = sample_until(
            lambda b=b: walker.run([b], "up"), lambda p: p[-1] == terminal_time
        )
        excursions.append([*piece[::-1], terminal_time])
    return excursions


def _spine_piece(
    walker: Walker, spine_level: float, *, prefer_top: bool
) -> list[float]:
    """Return the ``0`` to ``T`` piece that ends at the spine's valley."""
    terminal_time = walker.terminal_time
    if spine_level == 0.0:
        return [0.0, terminal_time]
    if prefer_top:
        piece = sample_until(
            lambda: walker.run([terminal_time, spine_level], "up"),
            lambda p: p[-1] == 0.0,
        )
        return piece[::-1]

    def make() -> list[float] | None:
        piece = walker.bottom_excursion()
        if piece[-1] != terminal_time:
            return None
        return _cut_at_last_downcrossing(piece, spine_level)

    cut = sample_until(make, lambda c: c is not None)
    assert cut is not None
    return cut


def _last_piece(walker: Walker, *, prefer_top: bool) -> list[float]:
    """Return the ``T`` to ``0`` piece that closes the contour."""
    terminal_time = walker.terminal_time
    if prefer_top:
        return sample_until(walker.top_excursion, lambda p: p[-1] == 0.0)
    piece = sample_until(walker.bottom_excursion, lambda p: p[-1] == terminal_time)
    return piece[::-1]


def _ages_contour(
    walker: Walker,
    ages: Sequence[float],
    spine_index: int | None,
    *,
    prefer_top: bool,
) -> tuple[list[float], int]:
    """Generate the contour of a tree with survivors of the given ``ages``.

    The draws are made in this order: the spine choice, the non-spine
    excursions, the spine piece, the last piece, the permutation.
    Return the contour and the index of the age assigned to the spine.
    """
    terminal_time = walker.terminal_time
    levels = _spine_levels(ages, terminal_time)
    spine_index = _choose_spine(walker, ages, levels, spine_index)
    excursions = _non_spine_excursions(walker, levels, spine_index)
    spine = _spine_piece(walker, levels[spine_index], prefer_top=prefer_top)
    last = _last_piece(walker, prefer_top=prefer_top)
    order = walker.rng.permutation(len(excursions))
    contour = join_pieces(spine, [excursions[int(k)] for k in order], last)
    if contour.count(terminal_time) != len(ages):
        msg = "contour does not have one visit to the terminal time per age"
        raise AssertionError(msg)
    return contour, spine_index


def simulate_contour_given_ages(  # noqa: PLR0913  # public signature
    birth_rate: RateInput,
    death_rate: RateInput,
    ages: Sequence[float],
    terminal_time: float | None = None,
    random_seed: int | None = None,
    *,
    spine_index: int | None = None,
    direction: Direction = "auto",
) -> SimulatedTree:
    r"""Simulate a birth-death tree whose survivors at ``T`` have the given ``ages``.

    Each non-spine survivor of age ``a`` contributes a ``T`` to ``T`` excursion
    ending at the valley ``T - a``; the spine survivor contributes the end of
    the ``0`` to ``T`` piece. The spine is chosen among the ages with
    probability proportional to $(I(T) - I(b)) / (1 + I(b))$,
    $b = T - a$, $I(t) = \int_0^t \mu e^{-\Gamma}$, unless ``spine_index`` is
    given or an age equals ``T`` (the root survived, which forces the spine).

    Parameters
    ----------
    birth_rate, death_rate
        Per-individual rates: floats (then ``terminal_time`` is required) or
        piecewise constant / linear rate-likes over ``[0, T]``.
    ages
        Ages at ``T`` of the survivors, each in ``(0, T]``.
    terminal_time
        The time ``T``. For rate-like inputs it must be ``None`` or equal to
        their common end time.
    random_seed
        Seed for reproducibility.
    spine_index
        Index in ``ages`` of the spine survivor; sampled when ``None``.
        Keyword-only.
    direction
        ``"auto"`` chooses the end of the end pieces; ``"top"`` or ``"bottom"``
        force it. All give the same distribution. Keyword-only.

    Returns
    -------
    SimulatedTree
        As :func:`simulate_contour_given_population`.

    Raises
    ------
    ValueError
        If ``ages`` is empty or has a value outside ``(0, T]``, more than one
        age equals ``T``, ``spine_index`` is out of range or inconsistent with
        an age equal to ``T``, all spine weights vanish (or that of
        ``spine_index``), the birth rate is identically zero while an age is
        below ``T``, or the rates,
        ``terminal_time`` or ``direction`` are invalid.

    """
    birth, death, horizon = resolve_rates(birth_rate, death_rate, terminal_time)
    prefer_top = _prefer_top(birth, death, horizon, direction)
    age_list = [float(a) for a in ages]
    if not age_list:
        msg = "ages must not be empty"
        raise ValueError(msg)
    if not all(a > 0.0 and (a <= horizon or close(a, horizon)) for a in age_list):
        msg = "ages must lie in (0, T]"
        raise ValueError(msg)
    at_top = [i for i, a in enumerate(age_list) if close(a, horizon)]
    if len(at_top) > 1:
        msg = "at most one age may equal T"
        raise ValueError(msg)
    if spine_index is not None:
        if not 0 <= spine_index < len(age_list):
            msg = "spine_index is out of range"
            raise ValueError(msg)
        if at_top and spine_index != at_top[0]:
            msg = "an age equal to T exists, so spine_index must point to it"
            raise ValueError(msg)
    if len(age_list) > len(at_top) and cumulative(birth, horizon) <= 0.0:
        msg = "birth_rate must not be identically zero when an age is below T"
        raise ValueError(msg)
    if spine_index is not None and not at_top:
        # A spine born after 0 needs a death below T; otherwise no piece exists.
        log_w = _log_spine_weights(birth, death, horizon, [age_list[spine_index]])
        if not np.isfinite(log_w[0]):
            msg = "the age at spine_index has zero spine weight"
            raise ValueError(msg)
    walker = Walker(birth, death, horizon, root_rng(random_seed, "contour"))
    contour, _ = _ages_contour(walker, age_list, spine_index, prefer_top=prefer_top)
    return contour_process_list_to_tree(
        contour,
        birth_rate=as_rate_like(birth_rate, horizon),
        death_rate=as_rate_like(death_rate, horizon),
    )
